BEGIN;

CREATE SCHEMA IF NOT EXISTS wildhatch;
REVOKE ALL ON SCHEMA wildhatch FROM PUBLIC;

DO $$ BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'wildhatch_runtime') THEN
    CREATE ROLE wildhatch_runtime NOLOGIN;
  END IF;
END $$;

CREATE TABLE wildhatch.profiles (
  token text PRIMARY KEY,
  data jsonb NOT NULL
);
CREATE INDEX wildhatch_username ON wildhatch.profiles (lower(data->>'name'));
CREATE TABLE wildhatch.wallets (
  address text PRIMARY KEY,
  token text UNIQUE NOT NULL REFERENCES wildhatch.profiles(token)
);
CREATE TABLE wildhatch.battles (
  id text PRIMARY KEY,
  result jsonb NOT NULL
);
CREATE TABLE wildhatch.wild_receipts (
  signature text PRIMARY KEY,
  owner text NOT NULL,
  item text NOT NULL,
  reward jsonb NOT NULL
);
CREATE TABLE wildhatch.listings (
  id text PRIMARY KEY,
  seller text NOT NULL REFERENCES wildhatch.profiles(token),
  beast text UNIQUE NOT NULL,
  price integer NOT NULL,
  currency text NOT NULL DEFAULT 'shards' CHECK (currency IN ('shards', 'WILD')),
  posted bigint GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX wildhatch_recent_listings ON wildhatch.listings (posted DESC);
CREATE TABLE wildhatch.sales (
  id text PRIMARY KEY,
  species text,
  price integer,
  sold_at bigint,
  currency text NOT NULL DEFAULT 'shards' CHECK (currency IN ('shards', 'WILD'))
);
CREATE INDEX wildhatch_recent_sales ON wildhatch.sales (sold_at DESC);
CREATE TABLE wildhatch.login_challenges (
  id text PRIMARY KEY,
  pending jsonb NOT NULL,
  expires bigint NOT NULL
);
CREATE INDEX wildhatch_challenge_expiry ON wildhatch.login_challenges (expires);
CREATE TABLE wildhatch.world (
  id integer PRIMARY KEY CHECK (id = 1),
  state jsonb NOT NULL DEFAULT '{}',
  last_wake timestamptz NOT NULL DEFAULT '-infinity'
);
INSERT INTO wildhatch.world (id) VALUES (1);
CREATE TABLE wildhatch.world_peers (
  token text PRIMARY KEY,
  state jsonb NOT NULL,
  zone integer GENERATED ALWAYS AS ((state->>'zone')::integer) STORED,
  x double precision GENERATED ALWAYS AS ((state->>'x')::double precision) STORED,
  z double precision GENERATED ALWAYS AS ((state->>'z')::double precision) STORED,
  touched bigint GENERATED ALWAYS AS ((state->>'touched')::bigint) STORED
);
CREATE INDEX wildhatch_nearby ON wildhatch.world_peers (zone, x, z);

-- Public Realtime events contain a wake signal only. Private game data is
-- fetched from the wallet/guest-checked server API.
CREATE FUNCTION wildhatch.notify_world() RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF to_regprocedure('realtime.send(jsonb,text,text,boolean)') IS NOT NULL THEN
    PERFORM realtime.send('{}'::jsonb, 'wake', 'wildhatch:world', false);
  END IF;
END;
$$;

REVOKE ALL ON TABLE wildhatch.profiles, wildhatch.wallets, wildhatch.battles,
  wildhatch.wild_receipts, wildhatch.listings, wildhatch.sales,
  wildhatch.login_challenges, wildhatch.world, wildhatch.world_peers FROM PUBLIC;
REVOKE ALL ON FUNCTION wildhatch.notify_world() FROM PUBLIC;
GRANT USAGE ON SCHEMA wildhatch TO wildhatch_runtime;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE wildhatch.profiles, wildhatch.wallets,
  wildhatch.battles, wildhatch.wild_receipts, wildhatch.listings, wildhatch.sales,
  wildhatch.login_challenges, wildhatch.world, wildhatch.world_peers TO wildhatch_runtime;
GRANT USAGE ON SEQUENCE wildhatch.listings_posted_seq TO wildhatch_runtime;
GRANT EXECUTE ON FUNCTION wildhatch.notify_world() TO wildhatch_runtime;

DO $$
DECLARE
  relation text;
  api_role text;
BEGIN
  FOREACH relation IN ARRAY ARRAY[
    'profiles', 'wallets', 'battles', 'wild_receipts', 'listings',
    'sales', 'login_challenges', 'world', 'world_peers'
  ] LOOP
    EXECUTE format('ALTER TABLE wildhatch.%I ENABLE ROW LEVEL SECURITY', relation);
    EXECUTE format(
      'CREATE POLICY runtime_access ON wildhatch.%I TO wildhatch_runtime USING (true) WITH CHECK (true)',
      relation
    );
  END LOOP;
  FOREACH api_role IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT FROM pg_roles WHERE rolname = api_role) THEN
      EXECUTE format('REVOKE ALL ON SCHEMA wildhatch FROM %I', api_role);
      EXECUTE format('REVOKE ALL ON FUNCTION wildhatch.notify_world() FROM %I', api_role);
    END IF;
  END LOOP;
END;
$$;

COMMIT;
